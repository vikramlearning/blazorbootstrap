namespace BlazorBootstrap;

/// <summary>
/// Defines the supported sizes for an <see cref="Avatar" />.
/// </summary>
public enum AvatarSize
{
    /// <summary>
    /// Indicates a small avatar.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Indicates a small avatar.")]
    Small,

    /// <summary>
    /// Indicates a medium avatar.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Indicates a medium avatar.")]
    Medium,

    /// <summary>
    /// Indicates a large avatar.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Indicates a large avatar.")]
    Large,

    /// <summary>
    /// Indicates an extra large avatar.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Indicates an extra large avatar.")]
    ExtraLarge
}
