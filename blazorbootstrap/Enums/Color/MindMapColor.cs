{
    /// <summary>
    /// Neutral lines and card borders, with no palette color.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Neutral lines and card borders, with no palette color.")]
    None,

    /// <summary>
    /// Bootstrap blue.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap blue.")]
    Blue,

    /// <summary>
    /// Bootstrap indigo.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap indigo.")]
    Indigo,

    /// <summary>
    /// Bootstrap purple.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap purple.")]
    Purple,

    /// <summary>
    /// Bootstrap pink.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap pink.")]
    Pink,

    /// <summary>
    /// Bootstrap red.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap red.")]
    Red,

    /// <summary>
    /// Bootstrap orange.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap orange.")]
    Orange,

    /// <summary>
    /// Bootstrap yellow.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap yellow.")]
    Yellow,

    /// <summary>
    /// Bootstrap green.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap green.")]
    Green,

    /// <summary>
    /// Bootstrap teal.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap teal.")]
    Teal,

    /// <summary>
    /// Bootstrap cyan.
    /// </summary>
    [AddedVersion("4.1.0")]
    [Description("Bootstrap cyan.")]
    Cyan
}
